temperature = int(input("Введите температуру на улице: "))

# Проверяем температуру и даём совет
if temperature < 0:
    print("На улице холодно, надень куртку")
elif temperature < 20:
    print("На улице прохладно")
else:
    print("На улице тепло, можно одеться легко")

# В зависимости от температуры программа выводит один из трёх результатов